#!/bin/sh
set -eu
cd "$(dirname "$0")"
mode=${1:-legacy}
case ${mode} in
--check|--live)
	uid=$(id -u)
	[ "${uid}" -eq 0 ] || { echo 'Check and live install need root.' >&2; exit 1; }
	sh ./wg-preflight ;;
--bootstrap) [ ! -e /etc/hostname.wg0 ] || { echo 'Use live mode on an existing server.' >&2; exit 1; } ;;
legacy) ;;
*) exit 2 ;;
esac
. ./local.conf
ADMIN_USER=${ADMIN_USER:?local.conf needs ADMIN_USER}
d=teoyujie.org
work=$(mktemp -d)
trap 'rm -rf "${work}"' EXIT
if [ "${mode}" = --check ]; then
	exec 3>&1
	echo 'Read-only live install preview. Private and generated bytes are not printed.'
fi

metadata() {
	stat -f '%Lp %Su:%Sg' "$1"
}

visible() {
	if [ "$1" = /etc/relayd.conf ]; then
		awk 'tolower($0) ~ /header[[:space:]]+set[[:space:]]+"authorization"/ { sub(/value[[:space:]]+".*/, "value \"[redacted]\"") } { print }' "$2"
	else
		cat "$2"
	fi
}

preview() {
	printf '\nFile: %s\n' "$1"
	before=/dev/null
	if [ -e "$1" ]; then before=$1; printf 'Current metadata: '; metadata "$1"; else echo 'Create file'; fi
	printf 'Write: %s\n' "${3:-keep current mode and owner, or use the current umask for a new file}"
	visible "$1" "${before}" > "${work}/before"
	visible "$1" "$2" > "${work}/after"
	diff -u -L "$1 (current)" -L "$1 (next)" "${work}/before" "${work}/after" || [ "$?" -eq 1 ]
	if ! cmp -s "${before}" "$2" && cmp -s "${work}/before" "${work}/after"; then echo 'Content differs; secret values are hidden.'; fi
}

write() {
	cat > "${work}/render"
	if [ "${mode}" = --check ]; then
		preview "$1" "${work}/render" "${2-}"
	elif [ "${2-}" = atomic ]; then
		cat "${work}/render" > "$1.new"
		mv -f "$1.new" "$1"
	else
		cat "${work}/render" > "$1"
	fi
}

ssh_keys() {
	printf '%s\n' "$2" > "${work}/input"
	sed '/^[[:space:]]*$/d; s#^[[:space:]]*#from="10.8.0.0/24,127.0.0.1" #' "${work}/input" > "${work}/content"
	write "$1" < "${work}/content"
}

generated() {
	printf 'Generated/private file: %s (%s; bytes not predicted)\n' "$1" "$2" >&3
	if [ -e "$1" ]; then metadata "$1" >&3; else printf 'Create file\n' >&3; fi
}

run() {
	if [ "${mode}" != --check ]; then "$@"; return; fi
	printf 'Action:' >&3; printf ' %s' "$@" >&3; printf '\n' >&3
	case $1 in
	useradd|usermod|passwd)
		for path in /etc/master.passwd /etc/passwd /etc/pwd.db /etc/spwd.db; do generated "${path}" "$1 account state"; done
		if [ "$1" = useradd ]; then generated /etc/group 'useradd group state'; fi ;;
	rcctl)
		case $2 in enable|disable) generated /etc/rc.conf.local "service flags from rcctl $2" ;; *) ;; esac ;;
	*) ;;
	esac
}

certificate() {
	if [ "${mode}" = --check ]; then
		generated "$2" 'generate private key; new mode 600, existing mode kept'
		generated "$1" 'create one-day certificate'
	else
		(umask 077 && openssl ecparam -genkey -name prime256v1 -out "$2" 2>/dev/null)
		openssl req -x509 -new -key "$2" -days 1 -subj /CN="$3" -out "$1"
	fi
}

removed_paths() {
	[ -d "$2" ] || return 0
	find "$2" -print > "${work}/old-tree"
	while IFS= read -r old; do
		next=$1${old#"$2"}
		if [ ! -e "${next}" ] && [ ! -L "${next}" ]; then printf 'Remove: %s\n' "${old}"; fi
	done < "${work}/old-tree"
}

tree_preview() {
	find "$1" -print > "${work}/tree-list"
	while IFS= read -r f; do
		target=$2${f#"$1"}
		file_meta=$(metadata "${f}")
		source_mode=${file_meta%% *}
		mask=$(umask)
		copy_mode=$(printf '%o' "$((0${source_mode} & ~0${mask}))")
		if [ -L "${f}" ]; then
			link=$(readlink "${f}")
			printf 'Symlink: %s -> %s\n' "${target}" "${link}"
		elif [ -d "${f}" ]; then
			printf 'Directory: %s\n' "${target}"
			if [ -d "${target}" ]; then metadata "${target}"; else echo 'Create directory'; fi
			printf 'Next metadata: %s\n' "${3:-mode ${copy_mode}, owner of the installer}"
		else
			preview "${target}" "${f}" "${3:-copy, mode ${copy_mode}, owner of the installer}"
		fi
	done < "${work}/tree-list"
	removed_paths "$1" "$2"
}

web_files() {
	if [ "${mode}" = --check ]; then tree_preview www /var/www/htdocs/server; else
		rm -rf /var/www/htdocs/server
		cp -R www /var/www/htdocs/server
	fi
}

cron_file() {
	cat > "${work}/cron"
	if [ "${mode}" = --check ]; then
		echo 'File: /var/cron/tabs/root'
		echo 'Write: root crontab, mode 600; generated spool headers omitted'
		diff -u -L 'root crontab (current)' -L 'root crontab (next)' "${work}/cron-before" "${work}/cron" || [ "$?" -eq 1 ]
	else
		crontab - < "${work}/cron"
	fi
}

put() {
	case ${KNOWN_IPS-} in *[\#\&\\]*) echo "put: KNOWN_IPS must not have #, & or a backslash, because sed would write other text" >&2; exit 1 ;; *) ;; esac
	out=$2.new
	[ "${mode:-}" != --check ] || out=${work}/put
	sed "s#@KNOWN_IPS@#${KNOWN_IPS}#g" "$1" > "${out}"
	chmod "${3:-644}" "${out}"
	if [ "${mode:-}" = --check ]; then preview "$2" "${out}" "replace, mode ${3:-644}, owner of the installer"; else mv -f "${out}" "$2"; fi
}

echo "${d}" > "${work}/content"
write /etc/myname < "${work}/content"
run hostname "${d}"

if [ "${mode}" = --check ] && ! id "${ADMIN_USER}" >/dev/null 2>&1 && [ ! -d /home/"${ADMIN_USER}" ]; then tree_preview /etc/skel /home/"${ADMIN_USER}" "useradd skeleton, owner ${ADMIN_USER}; mode from useradd defaults"; fi
if [ "${mode}" = --check ] && ! id deploy >/dev/null 2>&1 && [ ! -d /home/deploy ]; then tree_preview /etc/skel /home/deploy 'useradd skeleton, owner deploy; mode from useradd defaults'; fi
id "${ADMIN_USER-}" >/dev/null 2>&1 || run useradd -m -G wheel -s /bin/ksh "${ADMIN_USER}"
id deploy >/dev/null 2>&1 || run useradd -m -s /bin/sh deploy
if ! id "${ADMIN_USER}" >/dev/null 2>&1 || grep -q "^${ADMIN_USER}:\*:" /etc/master.passwd; then
	if [ -t 0 ]; then run passwd "${ADMIN_USER}"; else echo "Set the doas password: passwd ${ADMIN_USER}"; fi
fi
run install -d -o "${ADMIN_USER}" -m 700 /home/"${ADMIN_USER}"/.ssh
ssh_keys /home/"${ADMIN_USER}"/.ssh/authorized_keys "${ADMIN_KEY-}"
run chown "${ADMIN_USER}" /home/"${ADMIN_USER}"/.ssh/authorized_keys
run install -d -m 755 /home/deploy/.ssh
echo "from=\"10.8.0.0/24,127.0.0.1\",restrict,command=\"/usr/local/sbin/deploy-only\" ${DEPLOY_KEY-}" > "${work}/content"
write /home/deploy/.ssh/authorized_keys < "${work}/content"

for f in sbin/*; do put "${f}" /usr/local/sbin/"${f#sbin/}" 755; done
id tunnel >/dev/null 2>&1 || run useradd -d /home/tunnel -s /usr/local/sbin/tunnel-wait tunnel
run install -d -m 755 /home/tunnel /home/tunnel/.ssh
ssh_keys /home/tunnel/.ssh/authorized_keys "${TUNNEL_KEY:-}"
put etc/doas.conf /etc/doas.conf
put etc/sysctl.conf /etc/sysctl.conf
put etc/sshd_config /etc/ssh/sshd_config
put etc/httpd.conf /etc/httpd.conf
put etc/acme-client.conf /etc/acme-client.conf
put etc/smtpd.conf /etc/mail/smtpd.conf
put etc/unbound.conf /var/unbound/etc/unbound.conf
put etc/pf.conf /etc/pf.conf 600
put etc/relayd.conf /etc/relayd.conf 600
run sysctl -q net.inet.ip.forwarding=1

run install -d -o deploy -m 755 /var/www/web /var/www/web/site /var/www/web/apps
run install -d -o "${ADMIN_USER}" -m 755 /var/www/files/f
web_files


if [ ! -e /etc/ssl/"${d}".fullchain.pem ]; then certificate /etc/ssl/"${d}".fullchain.pem /etc/ssl/private/"${d}".key "${d}"; fi
if [ ! -e /etc/ssl/apps.crt ]; then certificate /etc/ssl/apps.crt /etc/ssl/private/apps.key mac.lavish."${d}"; fi
if [ ! -e /etc/mail/srs.conf ]; then
	if [ "${mode}" = --check ]; then
		generated /etc/mail/srs.conf 'create SRS key, mode 600'
	else
		srs_key=$(openssl rand -hex 32)
		(umask 077 && echo "srs key ${srs_key}" > /etc/mail/srs.conf)
	fi
fi
for a in contact postmaster ${ALIASES-}; do echo "${a}@${d} ${FORWARD_TO-}"; done > "${work}/content"
write /etc/mail/virtual < "${work}/content"
{
	sed '/^# BEGIN teoyujie.org/,/^# END teoyujie.org/d' /etc/mail/aliases
	echo "# BEGIN teoyujie.org (install.sh writes this block)"
	echo "root: contact"
	echo "contact: ${FORWARD_TO}"
	for a in ${ALIASES}; do echo "${a}: contact"; done
	echo "# END teoyujie.org"
} > "${work}/content"
write /etc/mail/aliases atomic < "${work}/content"

if [ "${mode}" != --live ] && [ "${mode}" != --check ]; then
	sh ./wg-config > /etc/hostname.wg0.new
	chmod 640 /etc/hostname.wg0.new
	if cmp -s /etc/hostname.wg0.new /etc/hostname.wg0 && ifconfig wg0 >/dev/null 2>&1; then
		rm /etc/hostname.wg0.new
	elif ! ifconfig wg0 >/dev/null 2>&1; then
		mv -f /etc/hostname.wg0.new /etc/hostname.wg0
		sh /etc/netstart wg0
	fi
fi

if grep -q ssh-alert /etc/syslog.conf; then
	if [ "${mode}" = --check ]; then preview /etc/syslog.conf /etc/syslog.conf 'unchanged'; fi
else
	{ cat /etc/syslog.conf; printf 'auth.info\t|/usr/local/sbin/ssh-alert\n'; } > "${work}/content"
	write /etc/syslog.conf < "${work}/content"
fi
if [ -e /var/cron/tabs/root ]; then crontab -l > "${work}/cron-before"; else : > "${work}/cron-before"; fi
{
	sed '/^# BEGIN teoyujie.org/,/^# END teoyujie.org/d' "${work}/cron-before"
	echo "# BEGIN teoyujie.org (install.sh writes this block)"
	cat etc/crontab
	echo "# END teoyujie.org"
} > "${work}/content"
cron_file < "${work}/content"
if [ "${mode}" = --check ]; then
	if [ -e /var/unbound/etc/blocklist.conf ]; then
		preview /var/unbound/etc/blocklist.conf /var/unbound/etc/blocklist.conf 'touch timestamps; content unchanged'
	else
		: > "${work}/content"
		write /var/unbound/etc/blocklist.conf < "${work}/content"
	fi
fi
run touch /var/unbound/etc/blocklist.conf

run sshd -t
run httpd -n
run smtpd -n
if [ "${mode}" = --check ]; then
	run unbound-anchor
	generated /var/unbound/db/root.key 'trust anchor refresh'
else
	unbound-anchor || echo "unbound-anchor did not update the root key, unbound keeps the key it has"
fi
run unbound-checkconf >/dev/null
run acme-client -n >/dev/null
run relayd -n >/dev/null
run pfctl -nf /etc/pf.conf
run pfctl -f /etc/pf.conf
for s in neurons_room slowcgi; do
	[ -x /etc/rc.d/"${s}" ] || continue
	run rcctl disable "${s}" >/dev/null
	if rcctl check "${s}" >/dev/null 2>&1; then run rcctl stop "${s}" >/dev/null; fi
done
if id fleet >/dev/null 2>&1; then
	run usermod -p '*' -s /sbin/nologin fleet
	keys=/home/fleet/.ssh/authorized_keys
	archive=${keys}.disabled
	n=0
	while [ -e "${archive}" ]; do n=$((n + 1)); archive=${keys}.disabled.${n}; done
	if [ -e "${keys}" ]; then
		if [ "${mode}" = --check ]; then
			preview "${keys}" /dev/null "rename to ${archive}"
			preview "${archive}" "${keys}" "rename from ${keys}; keep mode and owner"
		fi
		run mv -f "${keys}" "${archive}"
	fi
	if [ -e /usr/local/sbin/fleet-upload ]; then
		if [ "${mode}" = --check ]; then preview /usr/local/sbin/fleet-upload /usr/local/sbin/fleet-upload 'mode 000; content unchanged'; fi
		run chmod 000 /usr/local/sbin/fleet-upload
	fi
fi
run rcctl enable httpd relayd smtpd unbound >/dev/null
run rcctl restart sshd syslogd httpd relayd smtpd unbound >/dev/null
if [ "${mode}" != --live ] && [ "${mode}" != --check ]; then
	/usr/local/sbin/private-cert || echo "private-cert failed: cron tries again each hour"
	[ -s /var/unbound/etc/blocklist.conf ] || /usr/local/sbin/blocklist-update
fi

if [ "${mode}" = --check ]; then
	echo 'End of preview. No installed files, account state or services changed.'
	exit 0
fi
public_key=$(ifconfig wg0 | awk '$1 == "wgpubkey" { print $2 }')
echo "Done. WireGuard public key of the server: ${public_key}"
if [ "${mode}" != --live ] && [ -e /etc/hostname.wg0.new ]; then
	echo "wg0 restarts in 2 seconds. The VPN stops for some seconds."
	trap '' HUP
	nohup sh -c 'sleep 2; mv -f /etc/hostname.wg0.new /etc/hostname.wg0; ifconfig wg0 destroy; sh /etc/netstart wg0' >/dev/null 2>&1 &
fi
